function [f, g, h] = cedp_func(x, prob_k)
%CEDP_FUNC The CEDP suite: constrained engineering design problems.
%
%   x -----> ps x D, one candidate per ROW (the CEC2020RW convention, so the
%            harness feeds both suites through the same transpose)
%   f -----> ps x 1 objective, minimisation throughout
%   g -----> ng x ps inequality constraints, feasible where g <= 0
%   h -----> 0 x ps, this suite has no equality constraints
%
% The constraint blocks are built column-per-constraint, the way the formulas
% read, and transposed once at the end -- the orientation cec20rw_func returns
% and the one calculate_fitness expects. Returning ps x ng instead is wrong in a
% way that hides: it only shows when a batch happens to hold exactly ng
% candidates, and then every candidate is scored against another one's
% constraints.
%
% Formulations follow the sources the best-known values in cedp_par come
% from, with the constant sets those values were produced with. Three notes on
% choices a reader would otherwise have to reverse-engineer:
%
% DISCRETE VARIABLES are snapped here, not in the search. Plate thickness moves
% in 0.0625 in steps, gear teeth and disc counts are integers, disc thickness in
% 0.5 mm and clamping force in 10 N. The algorithm therefore optimises over a
% continuous box and never has to know; the objective it is scored on is the one
% of the SNAPPED design, which is what the published optima report.
%
% P9 (clutch brake) uses Rsr = 2/3 (ro^3 - ri^3)/(ro^2 - ri^2), the mean sliding
% radius as the original writes it. Much circulated code -- the CEC2020RW RC21
% among it -- carries (ro^2 * ri^2) in that denominator, which is off by a length
% squared and makes the two velocity constraints unreachable. Vsr comes out in
% mm/s here, so Vsr_max = 10 m/s enters as 1e4. The published optimum
% (ri, ro, t, F, Z) = (70, 90, 1, 600, 2) -> 0.235242 is feasible and optimal
% under either reading; they part only near the g4/g5 boundary.
%
% P10 (rolling element bearing) MAXIMISES dynamic capacity Cd in its sources; it
% is returned as -Cd so the whole suite minimises. Its phi_o involves an acos
% whose argument leaves [-1, 1] for geometrically impossible designs; the
% argument is clamped so such a point stays real and is judged by its
% constraints, instead of returning a complex number that max() would compare by
% magnitude.

    [ps, ~] = size(x);
    g = zeros(ps, 0);
    h = zeros(ps, 0);

    switch prob_k

    case 1      %% Welded beam design
        x1 = x(:, 1); x2 = x(:, 2); x3 = x(:, 3); x4 = x(:, 4);
        P = 6000; L = 14; E = 30e6; Gm = 12e6;
        tau_max = 13600; sig_max = 30000; del_max = 0.25;

        M  = P .* (L + x2 / 2);
        R  = sqrt(x2.^2 / 4 + ((x1 + x3) / 2).^2);
        J  = 2 * (sqrt(2) * x1 .* x2 .* (x2.^2 / 12 + ((x1 + x3) / 2).^2));
        t1 = P ./ (sqrt(2) * x1 .* x2);
        t2 = M .* R ./ J;
        tau   = sqrt(t1.^2 + 2 * t1 .* t2 .* x2 ./ (2 * R) + t2.^2);
        sigma = 6 * P * L ./ (x4 .* x3.^2);
        delta = 4 * P * L^3 ./ (E * x3.^3 .* x4);
        Pc    = (4.013 * E * sqrt(x3.^2 .* x4.^6 / 36) / L^2) ...
                .* (1 - (x3 / (2 * L)) * sqrt(E / (4 * Gm)));

        f = 1.10471 * x1.^2 .* x2 + 0.04811 * x3 .* x4 .* (14.0 + x2);
        g = [tau - tau_max, ...
             sigma - sig_max, ...
             x1 - x4, ...
             0.10471 * x1.^2 + 0.04811 * x3 .* x4 .* (14.0 + x2) - 5.0, ...
             0.125 - x1, ...
             delta - del_max, ...
             P - Pc];

    case 2      %% Pressure vessel design
        x1 = round(x(:, 1) / 0.0625) * 0.0625;   % shell plate, 0.0625 in steps
        x2 = round(x(:, 2) / 0.0625) * 0.0625;   % head plate
        x3 = x(:, 3); x4 = x(:, 4);

        f = 0.6224 * x1 .* x3 .* x4 + 1.7781 * x2 .* x3.^2 ...
            + 3.1661 * x1.^2 .* x4 + 19.84 * x1.^2 .* x3;
        g = [-x1 + 0.0193 * x3, ...
             -x2 + 0.00954 * x3, ...
             -pi * x3.^2 .* x4 - (4 / 3) * pi * x3.^3 + 1296000, ...
             x4 - 240];

    case 3      %% Tension/compression spring design
        x1 = x(:, 1); x2 = x(:, 2); x3 = x(:, 3);

        f = (x3 + 2) .* x2 .* x1.^2;
        g = [1 - x2.^3 .* x3 ./ (71785 * x1.^4), ...
             (4 * x2.^2 - x1 .* x2) ./ (12566 * (x2 .* x1.^3 - x1.^4)) ...
                + 1 ./ (5108 * x1.^2) - 1, ...
             1 - 140.45 * x1 ./ (x2.^2 .* x3), ...
             (x1 + x2) / 1.5 - 1];

    case 4      %% Speed reducer design
        x1 = x(:, 1); x2 = x(:, 2); x3 = round(x(:, 3));   % teeth are integer
        x4 = x(:, 4); x5 = x(:, 5); x6 = x(:, 6); x7 = x(:, 7);

        f = 0.7854 * x1 .* x2.^2 .* (3.3333 * x3.^2 + 14.9334 * x3 - 43.0934) ...
            - 1.508 * x1 .* (x6.^2 + x7.^2) + 7.4777 * (x6.^3 + x7.^3) ...
            + 0.7854 * (x4 .* x6.^2 + x5 .* x7.^2);
        g = [27 ./ (x1 .* x2.^2 .* x3) - 1, ...
             397.5 ./ (x1 .* x2.^2 .* x3.^2) - 1, ...
             1.93 * x4.^3 ./ (x2 .* x3 .* x6.^4) - 1, ...
             1.93 * x5.^3 ./ (x2 .* x3 .* x7.^4) - 1, ...
             sqrt((745 * x4 ./ (x2 .* x3)).^2 + 16.9e6) ./ (110 * x6.^3) - 1, ...
             sqrt((745 * x5 ./ (x2 .* x3)).^2 + 157.5e6) ./ (85 * x7.^3) - 1, ...
             x2 .* x3 / 40 - 1, ...
             5 * x2 ./ x1 - 1, ...
             x1 ./ (12 * x2) - 1, ...
             (1.5 * x6 + 1.9) ./ x4 - 1, ...
             (1.1 * x7 + 1.9) ./ x5 - 1];

    case 5      %% Three-bar truss design
        x1 = x(:, 1); x2 = x(:, 2);
        L = 100; P = 2; sigma = 2;
        den = sqrt(2) * x1.^2 + 2 * x1 .* x2;

        f = (2 * sqrt(2) * x1 + x2) * L;
        g = [(sqrt(2) * x1 + x2) ./ den * P - sigma, ...
             x2 ./ den * P - sigma, ...
             1 ./ (sqrt(2) * x2 + x1) * P - sigma];

    case 6      %% Cantilever beam design
        f = 0.0624 * sum(x(:, 1:5), 2);
        g = 61 ./ x(:, 1).^3 + 37 ./ x(:, 2).^3 + 19 ./ x(:, 3).^3 ...
            + 7 ./ x(:, 4).^3 + 1 ./ x(:, 5).^3 - 1;

    case 7      %% Gear train design
        n = round(x(:, 1:4));            % teeth counts are integer
        f = (1 / 6.931 - n(:, 3) .* n(:, 2) ./ (n(:, 1) .* n(:, 4))).^2;

    case 8      %% Car side impact design
        x1 = x(:, 1); x2 = x(:, 2); x3  = x(:, 3);  x4  = x(:, 4);
        x5 = x(:, 5); x6 = x(:, 6); x7  = x(:, 7);  x8  = x(:, 8);
        x9 = x(:, 9); x10 = x(:, 10); x11 = x(:, 11);

        f = 1.98 + 4.9 * x1 + 6.67 * x2 + 6.98 * x3 + 4.01 * x4 ...
            + 1.78 * x5 + 0.00001 * x6 + 2.73 * x7;
        g = [1.16 - 0.3717 * x2 .* x4 - 0.00931 * x2 .* x10 ...
                - 0.484 * x3 .* x9 + 0.01343 * x6 .* x10 - 1, ...
             0.261 - 0.0159 * x1 .* x2 - 0.188 * x1 .* x8 - 0.019 * x2 .* x7 ...
                + 0.0144 * x3 .* x5 + 0.0008757 * x5 .* x10 + 0.08045 * x6 .* x9 ...
                + 0.00139 * x8 .* x11 + 0.00001575 * x10 .* x11 - 0.32, ...
             0.214 + 0.00817 * x5 - 0.131 * x1 .* x8 - 0.0704 * x1 .* x9 ...
                + 0.03099 * x2 .* x6 - 0.018 * x2 .* x7 + 0.0208 * x3 .* x8 ...
                + 0.121 * x3 .* x9 - 0.00364 * x5 .* x6 + 0.0007715 * x5 .* x10 ...
                - 0.0005354 * x6 .* x10 + 0.00121 * x8 .* x11 ...
                + 0.00184 * x9 .* x10 - 0.02 * x2.^2 - 0.32, ...
             0.74 - 0.61 * x2 - 0.163 * x3 .* x8 + 0.001232 * x3 .* x10 ...
                - 0.166 * x7 .* x9 + 0.227 * x2.^2 - 0.32, ...
             28.98 + 3.818 * x3 - 4.2 * x1 .* x2 + 0.0207 * x5 .* x10 ...
                + 6.63 * x6 .* x9 - 7.7 * x7 .* x8 + 0.32 * x9 .* x10 - 32, ...
             33.86 + 2.95 * x3 + 0.1792 * x10 - 5.057 * x1 .* x2 ...
                - 11.0 * x2 .* x8 - 0.0215 * x5 .* x10 - 9.98 * x7 .* x8 ...
                + 22.0 * x8 .* x9 - 32, ...
             46.36 - 9.9 * x2 - 12.9 * x1 .* x8 + 0.1107 * x3 .* x10 - 32, ...
             4.72 - 0.5 * x4 - 0.19 * x2 .* x3 - 0.0122 * x4 .* x10 ...
                + 0.009325 * x6 .* x10 + 0.000191 * x11.^2 - 4, ...
             10.58 - 0.674 * x1 .* x2 - 1.95 * x2 .* x8 + 0.02054 * x3 .* x10 ...
                - 0.0198 * x4 .* x10 + 0.028 * x6 .* x10 - 9.9, ...
             16.45 - 0.489 * x3 .* x7 - 0.843 * x5 .* x6 + 0.0432 * x9 .* x10 ...
                - 0.0556 * x9 .* x11 - 0.000786 * x11.^2 - 15.7];

    case 9      %% Multiple disc clutch brake design
        ri = round(x(:, 1));                  % inner radius, 1 mm steps
        ro = round(x(:, 2));                  % outer radius, 1 mm steps
        t  = round(x(:, 3) / 0.5) * 0.5;      % disc thickness, 0.5 mm steps
        F  = round(x(:, 4) / 10) * 10;        % actuating force, 10 N steps
        Z  = round(x(:, 5));                  % number of friction surfaces

        Mf = 3; Ms = 40; Iz = 55; n = 250; Tmax = 15; s = 1.5; delta = 0.5;
        Vsrmax = 1e4; rho = 0.0000078; pmax = 1; mu = 0.6; Lmax = 30; delR = 20;

        dR3 = ro.^3 - ri.^3;
        dR2 = ro.^2 - ri.^2;
        Rsr = 2 / 3 * dR3 ./ dR2;
        Vsr = pi * Rsr * n / 30;
        A   = pi * dR2;
        Prz = F ./ A;
        w   = pi * n / 30;
        Mh  = 2 / 3 * mu * F .* Z .* dR3 ./ dR2;
        T   = Iz * w ./ (Mh + Mf);

        f = pi * dR2 .* t .* (Z + 1) * rho;
        g = [-ro + ri + delR, ...
             (Z + 1) .* (t + delta) - Lmax, ...
             Prz - pmax, ...
             Prz .* Vsr - pmax * Vsrmax, ...
             Vsr - Vsrmax, ...
             T - Tmax, ...
             s * Ms - Mh, ...
             -T];

    case 10     %% Rolling element bearing design
        Dm = x(:, 1); Db = x(:, 2); Z = round(x(:, 3));
        fi = x(:, 4); fo = x(:, 5);
        KDmin = x(:, 6); KDmax = x(:, 7);
        eps = x(:, 8); e = x(:, 9); zeta = x(:, 10);
        D = 160; d = 90; Bw = 30;

        T = D - d - 2 * Db;
        a = 0.5 * (D - d) - 0.75 * T;
        b = 0.5 * D - 0.25 * T - Db;
        c = 0.5 * d + 0.25 * T;
        arg = (a.^2 + b.^2 - c.^2) ./ (2 * a .* b);
        arg = min(1, max(-1, arg));           % keep impossible geometries real
        phi_o = 2 * pi - 2 * acos(arg);

        gamma = Db ./ Dm;
        fc = 37.91 * (1 + (1.04 * ((1 - gamma) ./ (1 + gamma)).^1.72 ...
                 .* (fi .* (2 * fo - 1) ./ (fo .* (2 * fi - 1))).^0.41).^(10 / 3)).^(-0.3) ...
             .* (gamma.^0.3 .* (1 - gamma).^1.39 ./ (1 + gamma).^(1 / 3)) ...
             .* (2 * fi ./ (2 * fi - 1)).^0.41;

        Cd = fc .* Z.^(2 / 3) .* Db.^1.8;
        big = Db > 25.4;                       % 1 in: the capacity law changes
        Cd(big) = 3.647 * fc(big) .* Z(big).^(2 / 3) .* Db(big).^1.4;

        f = -Cd;                               % the sources maximise Cd
        g = [Z - 1 - phi_o ./ (2 * asin(Db ./ Dm)), ...
             KDmin .* (D - d) - 2 * Db, ...
             2 * Db - KDmax .* (D - d), ...
             zeta * Bw - Db, ...
             0.5 * (D + d) - Dm, ...
             Dm - (0.5 + e) .* (D + d), ...
             eps .* Db - 0.5 * (D - Dm - Db), ...
             0.515 - fi, ...
             0.515 - fo];

    otherwise
        error('cedp_func:badIndex', ...
              'Problem index must be an integer in 1..10, got %s.', mat2str(prob_k));
    end

    f = f(:);
    g = g.';        % ng x ps, as the harness and the CEC2020RW suite have it
    h = h.';
end
